document.addEventListener('DOMContentLoaded', function () {
    // 1. Initialize Project Detail Image Slider (if Splide is available)
    var detailSliderEl = document.getElementById('project-detail-slider');
    if (detailSliderEl && typeof Splide !== 'undefined') {
        var detailSplide = new Splide('#project-detail-slider', {
            type: 'fade',
            rewind: true,
            arrows: false,
            pagination: false,
            speed: 600
        }).mount();

        var prevBtn = document.getElementById('gallery-prev-btn');
        var nextBtn = document.getElementById('gallery-next-btn');

        if (prevBtn) {
            prevBtn.addEventListener('click', function (e) {
                e.preventDefault();
                detailSplide.go('<');
            });
        }
        if (nextBtn) {
            nextBtn.addEventListener('click', function (e) {
                e.preventDefault();
                detailSplide.go('>');
            });
        }
    }

    // 2. Initialize Related Projects Carousel
    var relatedSliderEl = document.getElementById('related-projects-slider');
    if (relatedSliderEl && typeof Splide !== 'undefined') {
        var relatedSplide = new Splide('#related-projects-slider', {
            type: 'loop',
            perPage: 3,
            perMove: 1,
            gap: '24px',
            arrows: false,
            pagination: false,
            autoplay: true,
            interval: 4500,
            pauseOnHover: true,
            breakpoints: {
                991: {
                    perPage: 2,
                    gap: '18px'
                },
                575: {
                    perPage: 1,
                    gap: '16px'
                }
            }
        }).mount();

        var relPrevBtn = document.getElementById('related-prev-btn');
        var relNextBtn = document.getElementById('related-next-btn');

        if (relPrevBtn) {
            relPrevBtn.addEventListener('click', function (e) {
                e.preventDefault();
                relatedSplide.go('<');
            });
        }
        if (relNextBtn) {
            relNextBtn.addEventListener('click', function (e) {
                e.preventDefault();
                relatedSplide.go('>');
            });
        }
    }
});
</script>

