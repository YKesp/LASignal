            type: 'loop',
            start: 1,
            focus: 'center',
            autoWidth: true,
            gap: '24px',
            arrows: false,
            pagination: false,
            autoplay: false,
            speed: 600,
            easing: 'cubic-bezier(0.25, 1, 0.5, 1)',
            updateOnMove: true,
            trimSpace: false,
            breakpoints: {
                1400: {
                    gap: '20px'
                },
                991: {
                    gap: '16px'
                },
                575: {
                    gap: '12px'
                }
            }
        });

        serviceSplide.mount();

        var prevBtn = document.getElementById('service-prev-btn');
        var nextBtn = document.getElementById('service-next-btn');

        if (prevBtn) {
            prevBtn.addEventListener('click', function (e) {
                e.preventDefault();
                serviceSplide.go('<');
            });
        }
        if (nextBtn) {
            nextBtn.addEventListener('click', function (e) {
                e.preventDefault();
                serviceSplide.go('>');
            });
        }
    }
});
